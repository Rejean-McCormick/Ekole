ROOT = Path(__file__).resolve().parent
FORMAT = 'ekole.situation-orchestrable.design/0.3'
AUTHORING_FORMAT = 'ekole.prf22.authoring/0.3'
HANDOFF_FORMAT = 'ekole.prf22.handoff/0.3'
SOURCE_EXAMPLE = ROOT.parent / 'examples' / 'fete-sorciere-theorie.design.json'
VALID_THEORY_IDS = ('sandoval-2014','biggs-align','fourcid','laurillard','kobbe-2007','cast-2024')
LEARNING_TYPES = ('acquisition','inquiry','practice','discussion','collaboration','production')
FOURCID_COMPONENTS = ('none','learning_task','supportive_information','procedural_information','part_task_practice')


class DesignError(ValueError):
    pass


def sha(data: object) -> str:
    return hashlib.sha256(json.dumps(data, ensure_ascii=False, sort_keys=True, separators=(',', ':')).encode('utf-8')).hexdigest()


def clean(text, label: str, min_len: int = 12, max_len: int = 4000) -> str:
    if not isinstance(text, str) or not min_len <= len(text.strip()) <= max_len:
        raise DesignError(f'{label} : texte explicite requis ({min_len} à {max_len} caractères)')
    return text.strip()


def candidate_ref(owner: str, resource_id: str, source_note: str = '') -> dict:
    result = {'owner': owner, 'resource_id': resource_id, 'revision': 'unverified-local-snapshot', 'pin_status': 'unresolved'}
    if source_note:
        result['source_note'] = source_note
    return result


def select_theory(ids: list[str]) -> list[dict]:
    exemplar = json.loads(SOURCE_EXAMPLE.read_text(encoding='utf-8'))
    lookup = {t['id']: t for t in exemplar['pedagogical_model']['theory_refs']}
    if not ids or set(ids) - set(lookup):
        raise DesignError('Référence théorique manquante ou inconnue : ' + ', '.join(sorted(set(ids)-set(lookup))))
    return [deepcopy(lookup[k]) for k in sorted(set(ids))]


def validate_entry(ref: str, entry: dict, allowed_activity_refs: set[str]) -> dict:
    if not isinstance(entry, dict):
        raise DesignError(f'{ref} : carte théorique absente')
    acts = entry.get('activity_refs', [])
    if not isinstance(acts, list) or not acts or not set(acts) <= allowed_activity_refs or len(set(acts)) != len(acts):
        raise DesignError(f'{ref} : choisir au moins une activité valide pour cet objectif')
    requirement = entry.get('assessment_requires', 'individual_possible')
    if requirement not in ('individual_possible','peer_interaction'):
        raise DesignError(f'{ref} : condition d’évaluation inconnue')
    ids = entry.get('theory_ids', ['sandoval-2014','biggs-align'])
    select_theory(ids)
    learning_type = entry.get('learning_type', 'practice')
    if learning_type not in LEARNING_TYPES:
        raise DesignError(f'{ref} : type d’apprentissage inconnu')
    fourcid=entry.get('fourcid_component','none')
    if fourcid not in FOURCID_COMPONENTS:raise DesignError(f'{ref} : composante 4C/ID inconnue')
    try: minutes=int(entry.get('duration_minutes',15))
    except (TypeError,ValueError):raise DesignError(f'{ref} : durée indicative invalide')
    if not 1 <= minutes <= 180:raise DesignError(f'{ref} : durée indicative hors de 1–180 minutes')
    mandatory = ('conjecture_statement','expected_action','process','observation','evidence','criterion',
                 'disconfirmation','alternative','boundary','interpretation_limit')
    checked = dict(entry)
    for name in mandatory:
        checked[name] = clean(entry.get(name,''), f'{ref} · {name}')
    checked['activity_refs'] = list(acts)
    checked['assessment_requires'] = requirement
    checked['theory_ids'] = list(ids)
    checked['learning_type'] = learning_type
    checked['fourcid_component'] = fourcid
    checked['duration_minutes'] = minutes
    return checked


def parse_dependencies(source: str, valid_refs: set[str]) -> list[tuple[str,str,str]]:
    """Read optional lines: <activity_ref> > <activity_ref> : <handoff>.
    Ref tokens are generated by the catalog, not arbitrary access paths.
    """
    deps = []
    if not source.strip():
        return deps
    for i, line in enumerate(source.splitlines(), 1):
        if not line.strip():
            continue
        m = re.fullmatch(r'\s*(.+?)\s*>\s*(.+?)\s+:\s+(.+?)\s*', line)
        if not m:
            raise DesignError(f'Dépendance ligne {i} : attendu « réf-avant > réf-après : production »')
        before, after, handoff = (s.strip() for s in m.groups())
        if before not in valid_refs or after not in valid_refs:
            raise DesignError(f'Dépendance ligne {i} : activité inconnue')
        deps.append((before,after,clean(handoff,'Production transmise',4,400)))
    return deps


def _selected_people_role(draft: dict) -> list[dict]:
    roles = []
    for t in draft['participation']['teams']:
        name = str(t.get('suggested_role') or '').strip()
        if name and name not in [x['purpose'] for x in roles]:
            roles.append({'id': f'role-{len(roles)+1:02d}', 'purpose': f'Rôle narratif proposé : {name}'})
    if not roles:
        roles = [{'id':'role-01','purpose':'Participant à la mission (rôle narratif à revoir)'}]
    return roles


def build_design(draft: dict, theory_entries: dict[str,dict], dependency_lines: str = '') -> dict:
    """Build a self-contained candidate blueprint, preserving all ownership boundaries."""
    validate_draft(draft)
    links = draft['learning_objective_links']
    activities = draft['activity_bindings']
    if not links:
        raise DesignError('Sélectionner au moins un objectif du répertoire indépendant')
    if not activities:
        raise DesignError('Sélectionner au moins une activité')
    known = {a['activity_ref'] for a in activities}
    if set(theory_entries) - {x['objective_ref'] for x in links}:
        raise DesignError('Cartes d’objectifs obsolètes : retirer les anciennes références')
    entries = {x['objective_ref']: validate_entry(x['objective_ref'], theory_entries.get(x['objective_ref']), known) for x in links}
    used_activities = {ref for item in entries.values() for ref in item['activity_refs']}
    if used_activities != known:
        raise DesignError('Certaines activités ne sont reliées à aucun objectif : ' + ', '.join(sorted(known-used_activities)))
    obj_ids = {x['objective_ref']:f'obj-{i:02d}' for i,x in enumerate(links, 1)}
    act_ids = {a['activity_ref']:f'act-{i:02d}' for i,a in enumerate(activities, 1)}
    dep_candidates = parse_dependencies(dependency_lines, known)
    ctx = draft['world_context']
    raw_context = draft['source']
    reality = {'fictif':'fiction','réel':'real','mixte':'mixed'}[ctx['reality']]
    roles = _selected_people_role(draft)
    obj_rows = [{'id': obj_ids[link['objective_ref']], 'reference': candidate_ref('Kontexte',link['objective_ref'],link['source_relpath'])} for link in links]
    assigned_obj_ids = {a: [] for a in known}
    for ref,entry in entries.items():
        for a in entry['activity_refs']:
            assigned_obj_ids[a].append(obj_ids[ref])
    activity_rows = []
    for a in activities:
        ref = a['activity_ref']
        activity_rows.append({
            'id':act_ids[ref], 'exercise_ref':candidate_ref('Kontexte',ref,a['source_relpath']),
            'objectives':assigned_obj_ids[ref], 'role_ids':[r['id'] for r in roles],
            'duration_minutes':max(entries[ref]['duration_minutes'] for ref in entries if a['activity_ref'] in entries[ref]['activity_refs']),
            'station':{'teams_per_instance':1, 'max_parallel_instances':draft['participation']['parallel_posts_per_activity'], 'materials_review_required':True},
            'solo_fallback':'Documents ou indices fournis sans prétendre démontrer une interaction entre pairs.',
            'group_fallback':'Transmission différée supervisée si les équipes ne peuvent pas se rencontrer.',
            'contextualization':a['title'],
        })
    used_theory_ids = sorted({id for entry in entries.values() for id in entry['theory_ids']})
    didactics = []
    for a in activities:
        related = [e for e in entries.values() if a['activity_ref'] in e['activity_refs']]
        didactics.append({
            'activity_id': act_ids[a['activity_ref']],
            'learning_types': sorted(set(e['learning_type'] for e in related)),
            'four_cid_components':sorted({e['fourcid_component'] for e in related if e['fourcid_component']!='none'}),
            'pedagogical_rationale':' ; '.join(e['conjecture_statement'] for e in related),
        })
    conditions=[];conjectures=[];evidence=[];alignments=[]
    for idx,link in enumerate(links, 1):
        original = link['objective_ref']; e = entries[original]
        oid = obj_ids[original]; aid = [act_ids[a] for a in e['activity_refs']]; ev_id=f'evidence-{idx:02d}'; pid=f'process-{idx:02d}'
        conditions.append({'objective_id':oid,'assessment_requires':e['assessment_requires'],'interpretation_limit':e['interpretation_limit']})
        conjectures.append({
            'id':f'conj-{idx:02d}', 'conjecture_statement':e['conjecture_statement'],
            'theoretical_basis_ids':sorted(set(e['theory_ids'])),
            'design_activity_ids':aid,'intended_objective_ids':[oid],
            'mediating_processes':[{'id':pid,'description':e['process'],'observation_strategy':e['observation']}],
            'boundary_conditions':[e['boundary']],
            'disconfirmation_signals':[e['disconfirmation']],
            'alternative_explanations':[e['alternative']],
            'validation_status':'untested',
        })
        evidence.append({'id':ev_id,'description':e['evidence'],'produced_by_activity_ids':aid,
                         'interpretation_limits':[e['interpretation_limit']],'storage_boundary':'external_only'})
        alignments.append({'id':f'alignment-{idx:02d}','objective_id':oid,'activity_ids':aid,
                           'expected_learner_actions':[e['expected_action']],'process_ids':[pid],
                           'evidence_id':ev_id,'criteria':[e['criterion']],
                           'assessed_modes':['collaborative'] if e['assessment_requires']=='peer_interaction' else ['solo','collaborative'],
                           'assessment_authority':'teacher','assessment_status':'planned_only'})
    exemplar = json.loads(SOURCE_EXAMPLE.read_text(encoding='utf-8'))
    example_contract = exemplar['pedagogical_model']['adaptation_contract']
    variants=[];org_variants=[]
    for n in sorted({1,8,30,draft['participation']['participant_count']}):
        solo = n==1
        preserve=[obj_ids[ref] for ref,e in entries.items() if not solo or e['assessment_requires']!='peer_interaction']
        exclude=[obj_ids[ref] for ref,e in entries.items() if solo and e['assessment_requires']=='peer_interaction']
        strategy = ('Parcours individuel et ressources documentaires de substitution, sans preuve de collaboration entre pairs.' if solo
                    else f'Organisation candidate pour {n} enfants, groupes et matériel à confirmer par l’enseignant.')
        variants.append({'learners':n,'mode':'solo' if solo else 'collaborative',
                         'change_notes':[strategy],'preserved_objective_ids':preserve,
                         'non_assessable_objective_ids':exclude,'teacher_approval_required':True,'resources_confirmed':False})
        org_variants.append({'learners':n,'strategy':strategy,'requires_teacher_review':True})
    premise = raw_context['problem'] or raw_context['title']
    cultural_frame = ctx['cultural_frame']
    document = {
        'format':FORMAT, 'status':'design_only',
        'id':'ekole-prf22-'+sha({'source':raw_context['reference'],'ctx':ctx,'activities':[a['activity_ref'] for a in activities],'objectives':list(entries)})[:16],
        'title': raw_context['title']+' — conception candidate',
        'context':{
            'reality_mode':reality,'epoch':ctx['epoch'],'place':ctx['place'],
            'language':ctx['language'],'cultural_frame':cultural_frame,
            'source_situation':candidate_ref('Kontexte',raw_context['reference'],raw_context['source_relpath']),
            'culture_refs':[], 'narrative_premise':premise if len(premise)>5 else 'Situation à contextualiser par un enseignant.',
            'review_status':'not_evaluated',
        },
        'learning':{'objectives':obj_rows, 'activity_catalog_ownership':'external'},
        'roles':roles,'activities':activity_rows,
        'dependencies':[{'before':act_ids[a],'after':act_ids[b],'handoff':txt} for a,b,txt in dep_candidates],
        'organization':{'min_learners':1,'max_learners':30,
                        'preferred_team_size':draft['participation']['maximum_per_team'],
                        'adaptations':org_variants,'human_confirm_resources':True},
        'evidence':{'expected_artifacts':[e['evidence'] for e in entries.values()],
                    'teacher_validation':True,'student_results_stored_here':False},
        'governance':{'access_authority':'external_required','execution_authority':'external_required',
                      'publication_authorized':False,'activation_authorized':False,
                      'student_data_included':False,'review_status':'not_evaluated'},
        'pedagogical_model':{
            'theory_refs':select_theory(used_theory_ids),'objective_conditions':conditions,
            'activity_didactics':didactics,'conjectures':conjectures,
            'evidence_design':evidence,'alignment':alignments,
            'adaptation_contract':{'invariants':deepcopy(example_contract['invariants']),'variants':variants},
            'research_plan':deepcopy(exemplar['pedagogical_model']['research_plan']),
        },
    }
    errors, used_schema = validate_document(document)
    if errors:
        raise DesignError('PRF-22 non conforme :\n- '+'\n- '.join(errors[:24]))
    return document


def authoring_state(draft: dict, theory_entries: dict, dependency_lines: str = '', catalog_root: Path | None = None) -> dict:
    validate_draft(draft)
    return {'format':AUTHORING_FORMAT,'status':'design_only','draft':draft,
            'theory_entries':deepcopy(theory_entries),'dependency_lines':dependency_lines,
            'source_observations':observe_catalogue_sources(catalog_root,draft) if catalog_root else []}


def load_authoring(path: str | Path) -> dict:
    file = Path(path)
    if file.stat().st_size > 2_000_000:
        raise DesignError('Brouillon trop volumineux')
    d = json.loads(file.read_text(encoding='utf-8'))
    if d.get('format') != AUTHORING_FORMAT or d.get('status') != 'design_only':
        raise DesignError('Format de brouillon PRF-22 inconnu')
    validate_draft(d['draft'])
    if not isinstance(d.get('theory_entries'), dict) or not isinstance(d.get('dependency_lines'), str):
        raise DesignError('Champs de conception invalides')
    return d


def make_handoff(design: dict, plan: dict, observed_sources: list[dict] | None = None) -> dict:
    errors,_ = validate_document(design)
    if errors:
        raise DesignError('Kristal non conforme, export interdit : '+errors[0])
    validate_draft(plan)
    return {'format':HANDOFF_FORMAT,'status':'proposal_only_not_authorized',
            'design_id':design['id'],'design_sha256':'sha256:'+sha(design),
            'planning_source_format':plan['format'],
            'selected_learners':plan['participation']['participant_count'],
            'organization_candidate':plan['participation'],
            'source_observations':observed_sources or [],
            'owner_hints':plan['authorities'],
            'teacher_review_required':True,'material_confirmed':False,
            'orgo_world_created':False,'konnaxion_project_created':False,
            'session_admitted':False,'permissions_granted':False,
            'student_data_included':False,
            'notice':'Document de préparation hors ligne. Aucun endpoint ou droit runtime accordé.'}


def observe_catalogue_sources(catalog_root: Path, draft: dict) -> list[dict]:
    """Compute informational hashes of local files, never mark them pinned/qualified."""
    relpaths = sorted({draft['source']['source_relpath'],
                        *[a['source_relpath'] for a in draft['activity_bindings']],
                        *[o['source_relpath'] for o in draft['learning_objective_links']]})
    results=[]
    root = catalog_root.resolve()
    for rel in relpaths:
        source=(root/rel).resolve()
        if not source.is_relative_to(root) or not source.is_file():
            raise DesignError('Source Kontexte manquante ou chemin invalide : '+rel)
        results.append({'owner':'Kontexte','relative_path':rel,
                        'observed_sha256':'sha256:'+hashlib.sha256(source.read_bytes()).hexdigest(),
                        'pin_status':'unresolved', 'qualification':'not_checked_with_owner'})
    return results


def _write_json(path: Path, data: object):
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2, sort_keys=False)+'\n',encoding='utf-8',newline='\n')


def export_pack(folder: str|Path, design: dict, draft: dict, entries: dict, dependency_lines: str,
                catalog_root: Path | None = None) -> Path:
    """Write one immutable, non-overwriting dossier with blueprint, handoff, authoring and review checklist."""
    errors, schema_checked = validate_document(design)
    if errors:
        raise DesignError('Ne peut exporter : '+ '; '.join(errors[:5]))
    observed = observe_catalogue_sources(catalog_root, draft) if catalog_root else []
    handoff=make_handoff(design,draft,observed)
    root=Path(folder)
    root.mkdir(parents=True,exist_ok=True)
    stamp=datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S%fZ')
    target=root/f'prf22-{design["id"]}-{stamp}'
    target.mkdir(exist_ok=False)
    try:
        _write_json(target/'kristal-situation.design.json',design)
        _write_json(target/'plan-organisation.proposition.json',handoff)
        _write_json(target/'brouillon-reedition.json',authoring_state(draft,entries,dependency_lines,catalog_root))
        if catalog_root:
            catalogue=load_catalogue(catalog_root)
            base=draft['world_context'];source=draft['source']['reference']
            activity_refs=[a['activity_ref'] for a in draft['activity_bindings']]
            objective_refs=[o['objective_ref'] for o in draft['learning_objective_links']]
            plans=target/'organisations-candidates'
            plans.mkdir()
            for n in sorted({1,8,30,draft['participation']['participant_count']}):
                adapted=compose_draft(catalogue,source,activity_refs,n,draft['participation']['maximum_per_team'],
                                      epoch=base['epoch'],cultural_frame=base['cultural_frame'],
                                      setting=base['place'],reality=base['reality'],language=base['language'],
                                      objectives=objective_refs,parallel_posts=draft['participation']['parallel_posts_per_activity'])
                _write_json(plans/f'plan-{n:02d}-participants.json',adapted)
        (target/'APERCU.txt').write_text(format_preview(draft),encoding='utf-8',newline='\n')
        review = ('PRF-22 — REVUES HUMAINES OBLIGATOIRES\n\n'
                  '[ ] Alignement réel objectifs / activités / preuves / critères\n'
                  '[ ] Validité des conjectures, prérequis, difficultés et résultats\n'
                  '[ ] Exactitude culturelle / historique, provenance et licences\n'
                  '[ ] Inclusion, accessibilité, langues et supports\n'
                  '[ ] Organisation des équipes, postes, temps, matériel, supervision\n'
                  '[ ] Sources externes résolues et autorité de publication\n'
                  '[ ] Permissions Konnaxion et admission Orgo (non réalisées ici)\n\n'
                  'Le dossier n’autorise aucune séance et ne mesure aucun apprentissage.\n')
        (target/'REVUE_ENSEIGNANT.txt').write_text(review,encoding='utf-8',newline='\n')
        report = {'format':'ekole.prf22.local-check/0.3','checked_at_utc':datetime.now(timezone.utc).isoformat(),
                  'schema_validation':'full_jsonschema' if schema_checked else 'portable_subset_and_semantic',
                  'semantic_validation':'pass','pedagogical_qualification':'not_performed',
                  'runtime_authority':'none','design_sha256':'sha256:'+sha(design)}
        _write_json(target/'VALIDATION_LOCALE.json',report)
    except Exception:
        # Files are only inside freshly created target, safe to remove in case of I/O failure.
        import shutil
        shutil.rmtree(target)
        raise
    return target
