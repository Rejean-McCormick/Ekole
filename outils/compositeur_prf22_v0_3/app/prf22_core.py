"""PRF-22 v0.3 — composer a design-only Kristal from Kontexte and teacher notes.

No network, operational authority, student identity, educational judgement, or automatic
publication. All external resource refs are explicitly unresolved; local hashes in
handoffs are observations, never source-owner pins.
"""
from __future__ import annotations

